  "<!doctype html>",
  '<html lang="en"><head><meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width,initial-scale=1">',
  "<title>bundant monitor</title>",
  "<style>",
  ":root{color-scheme:dark}body{margin:0;font:13px/1.45 ui-monospace,SFMono-Regular,Menlo,monospace;background:#0f1115;color:#d6dae2}",
  "header{display:flex;gap:12px;align-items:center;padding:10px 14px;background:#161a21;border-bottom:1px solid #232a35;position:sticky;top:0}",
  "header b{color:#8ab4f8}nav button{background:#1d232c;color:#c9d1d9;border:1px solid #2b333f;border-radius:6px;padding:4px 10px;cursor:pointer;font:inherit}",
  "nav button.on{background:#2b3b52;border-color:#3d5a86;color:#fff}main{padding:14px}h3{margin:14px 0 6px;color:#9aa4b2;font-weight:600}",
  "table{border-collapse:collapse;width:100%}th,td{text-align:left;padding:3px 8px;border-bottom:1px solid #1e242e;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}",
  "th{color:#8b94a3;font-weight:600}tr:hover td{background:#171c24}.up{color:#7ee787}.down{color:#ff7b72}.dim{color:#6b7280}",
  "pre{background:#12161d;border:1px solid #1f2531;border-radius:6px;padding:8px;overflow:auto;max-height:60vh;margin:0}",
  "select,input,button{background:#1d232c;color:#d6dae2;border:1px solid #2b333f;border-radius:6px;padding:3px 6px;font:inherit}",
  ".row{display:flex;gap:8px;align-items:center;flex-wrap:wrap;margin-bottom:8px}",
  "svg{vertical-align:middle}</style></head><body>",
  "<header><b>bundant monitor</b><nav id=nav></nav>",
  '<span class=dim id=meta></span><label class=dim><input type=checkbox id=auto checked> auto 5s</label>',
  "<button id=refresh>refresh</button></header><main id=main></main>",
  "<script>",
  "var TABS=['containers','stats','logs','proxy','events'];var tab='containers';var timer=null;",
  "var hist={};function el(id){return document.getElementById(id)}",
  "function esc(s){return String(s==null?'':s).replace(/[&<>]/g,function(c){return {'&':'&amp;','<':'&lt;','>':'&gt;'}[c]})}",
  "function spark(arr){if(!arr||arr.length<2)return '<span class=dim>-</span>';var w=90,h=16,m=Math.max.apply(null,arr)||1;",
  "var pts=arr.map(function(v,i){return (i*(w/(arr.length-1))).toFixed(1)+','+(h-(v/m)*(h-2)-1).toFixed(1)}).join(' ');",
  "return '<svg width='+w+' height='+h+'><polyline fill=none stroke=#8ab4f8 stroke-width=1.4 points=\"'+pts+'\"/></svg>'}",
  "function get(u){return fetch(u).then(function(r){return r.json()})}",
  "function rowsFor(hosts,keys,fn){return hosts.map(function(h){",
  "if(!h.ok)return '<h3>'+esc(h.host)+' <span class=down>'+esc(h.error)+'</span></h3>';",
  "return '<h3>'+esc(h.host)+'</h3><table><tr>'+keys.map(function(k){return '<th>'+k+'</th>'}).join('')+'</tr>'+h.rows.map(fn).join('')+'</table>'}).join('')}",
  "function renderContainers(d){var o=d.hosts.map(function(h){",
  "if(!h.ok)return '<h3>'+esc(h.host)+' <span class=down>'+esc(h.error)+'</span></h3>';",
  "return '<h3>'+esc(h.host)+'</h3><table><tr><th>name</th><th>image</th><th>status</th><th>ports</th></tr>'+",
  "h.rows.map(function(r){var cls=/^Up/.test(r.status)?'up':'down';",
  "return '<tr><td>'+esc(r.name)+'</td><td class=dim>'+esc(r.image)+'</td><td class='+cls+'>'+esc(r.status)+'</td><td class=dim>'+esc(r.ports)+'</td></tr>'}).join('')+'</table>'}).join('');",
  "el('main').innerHTML='<h3 class=dim>containers on '+d.hosts.length+' host(s)</h3>'+o}",
  "function renderStats(d){var o=d.hosts.map(function(h){",
  "if(!h.ok)return '<h3>'+esc(h.host)+' <span class=down>'+esc(h.error)+'</span></h3>';",
  "var mem=h.rows.map(function(r){hist[h.host]=hist[h.host]||[];return r}).length;",
  "h.rows.forEach(function(r){var k=h.host+'|'+r.name;hist[k]=hist[k]||[];",
  "var v=parseFloat(r.memPct);if(isFinite(v)){hist[k].push(v);if(hist[k].length>60)hist[k].shift()}});",
  "return '<h3>'+esc(h.host)+'</h3><table><tr><th>name</th><th>cpu</th><th>mem</th><th>mem%</th><th>pids</th><th>trend</th></tr>'+",
  "h.rows.map(function(r){return '<tr><td>'+esc(r.name)+'</td><td>'+esc(r.cpu)+'</td><td>'+esc(r.mem)+'</td><td>'+esc(r.memPct)+'</td><td>'+esc(r.pids)+'</td><td>'+spark(hist[h.host+'|'+r.name])+'</td></tr>'}).join('')+'</table>'}).join('');",
  "el('main').innerHTML='<h3 class=dim>snapshots while this page is open (no host-side history)</h3>'+o}",
  "function renderProxy(d){var o=d.hosts.map(function(h){",
  "if(!h.ok)return '<h3>'+esc(h.host)+' <span class=down>'+esc(h.error)+'</span></h3>';",
  "return '<h3>'+esc(h.host)+'</h3><pre>'+esc(h.rows.join('\\n'))+'</pre>'}).join('');",
  "el('main').innerHTML=o||'<span class=dim>no proxy running</span>'}",
  "function renderEvents(d){el('main').innerHTML='<div class=row><span>host</span><select id=eh>'+d.hosts.map(function(h){return '<option>'+esc(h)+'</option>'}).join('')+'</select>",
  "'<span>since</span><input id=es size=8 value=2h><button id=ego>load</button></div><pre id=eout class=dim>press load</pre>';",
  "el('ego').onclick=function(){var h=el('eh').value,s=el('es').value;get('/api/events?host='+encodeURIComponent(h)+'&since='+encodeURIComponent(s)).then(function(r){",
  "el('eout').textContent=r.ok?r.lines.join('\\n'):('error: '+r.error)})}}",
  "var LOGSTATE={};",
  "function renderLogs(d){var first=!el('lh');",
  "var opts=[];Object.keys(d.byHost).forEach(function(h){d.byHost[h].forEach(function(c){opts.push([h,c])})});",
  "var selHTML=opts.map(function(o){return '<option value=\"'+esc(o[0])+'|'+esc(o[1])+'\">'+esc(o[0])+' / '+esc(o[1])+'</option>'}).join('');",
  "el('main').innerHTML='<div class=row><span>target</span><select id=lh>'+selHTML+'</select>'+",
  "'<span>tail</span><input id=lt size=5 value=200><label class=dim><input type=checkbox id=lauto checked> auto 2s</label></div>'+(first?'':'')+'<pre id=lout>loading…</pre>';",
  "el('lh').onchange=loadLogs;el('lt').onchange=loadLogs;setInterval(function(){if(el('lauto')&&el('lauto').checked)loadLogs()},2000);loadLogs()}",
  "function loadLogs(){var sel=el('lh');if(!sel)return;var p=sel.value.split('|');var t=el('lt')?el('lt').value:200;",
  "get('/api/logs?host='+encodeURIComponent(p[0])+'&container='+encodeURIComponent(p[1])+'&tail='+t).then(function(r){",
  "var o=el('lout');if(!o)return;o.textContent=r.ok?r.text:('error: '+r.error);o.scrollTop=o.scrollHeight})}",
  "function render(){var t0=Date.now();if(tab==='containers')get('/api/snapshot').then(function(d){renderContainers(d);el('meta').textContent=d.hosts.length+' hosts, '+(Date.now()-t0)+'ms'})",
  "else if(tab==='stats')get('/api/stats').then(renderStats)",
  "else if(tab==='proxy')get('/api/proxy').then(renderProxy)",
  "else if(tab==='events')get('/api/hosts').then(renderEvents)",
